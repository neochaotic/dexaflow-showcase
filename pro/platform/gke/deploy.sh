#!/usr/bin/env bash
# Install or upgrade Dexaflow Pro on the GKE demo cluster.
#
# The easy path runs Postgres and Redis inside the cluster (same manifests as
# the local environment, with a generated password). For a production-shaped
# setup with Cloud SQL and Memorystore, follow the upstream recipe in
# deploy/k8s/03-managed.sh of the dexaflow repository.
source "$(dirname "$0")/lib-gke.sh"
need kubectl; need helm; need openssl
[[ -f "${GKE_ENV}" ]] || die "run 'make gke-up' first"

run gcloud container clusters get-credentials "${GKE_CLUSTER}" --zone "${GKE_ZONE}" --project "${GCP_PROJECT}"
run kubectl create namespace "${NAMESPACE}" --dry-run=client -o yaml | kubectl apply -f -

if [[ ! -f "${GKE_SECRETS}" ]]; then
  log "Generating credentials into .out/gke-secrets.yaml (gitignored, reused on every deploy)"
  PG_PASSWORD="$(openssl rand -hex 16)"
  ADMIN_PASSWORD="$(openssl rand -base64 18 | tr -d '/+=')"
  umask 077
  cat > "${GKE_SECRETS}" <<SECRETS
# Generated by deploy.sh. Do not commit. Admin login: ${ADMIN_EMAIL} / ${ADMIN_PASSWORD}
database:
  url: postgres://dexaflow:${PG_PASSWORD}@postgres:5432/dexaflow?sslmode=disable
redis:
  url: redis://redis:6379/0
auth:
  jwtSecret: $(openssl rand -base64 48 | tr -d '\n')
secretKey: $(openssl rand -hex 32)
bootstrap:
  password: ${ADMIN_PASSWORD}
SECRETS
  echo "DEXAFLOW_PASSWORD=${ADMIN_PASSWORD}" >> "${GKE_ENV}"
fi
PG_PASSWORD="$(sed -n 's|.*postgres://dexaflow:\([^@]*\)@.*|\1|p' "${GKE_SECRETS}")"

log "Deploying in-cluster Postgres and Redis"
sed -e "s|__POSTGRES_IMAGE__|${POSTGRES_IMAGE}|" -e "s|__REDIS_IMAGE__|${REDIS_IMAGE}|" \
    -e "s|__PG_PASSWORD__|${PG_PASSWORD}|" \
  "${REPO_ROOT}/pro/platform/local/datastores.yaml" | kubectl apply -n "${NAMESPACE}" -f -
run kubectl -n "${NAMESPACE}" rollout status deploy/postgres --timeout=300s
run kubectl -n "${NAMESPACE}" rollout status deploy/redis --timeout=180s

log "Installing Dexaflow Pro ${DEXAFLOW_VERSION}"
run helm upgrade --install "${RELEASE}" "${DEXAFLOW_CHART}" --version "${DEXAFLOW_VERSION}" \
  -n "${NAMESPACE}" \
  -f "${REPO_ROOT}/pro/platform/base/values.yaml" \
  -f "${REPO_ROOT}/pro/platform/gke/values-gke.yaml" \
  -f "${GKE_SECRETS}" \
  --set taskNamespace="${NAMESPACE}" \
  --set-string "taskServiceAccount.annotations.iam\.gke\.io/gcp-service-account=${TASK_GSA}" \
  --wait --timeout 10m

log "Deployed. Open the UI with: make gke-ui   (then http://localhost:${GKE_UI_PORT})"
log "Admin login is in the first line of .out/gke-secrets.yaml"
log "Run the demos with: make gke-demo"
